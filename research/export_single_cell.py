#!/usr/bin/env python3
"""Export the notebook as one Python file.

    python research/export_single_cell.py

Kaggle wants a notebook, but pasting a single cell is sometimes easier
than importing an .ipynb.  The cells are written to run in order in one
namespace -- that is exactly what `research/run_notebook_local.py` does
with the same file -- so concatenating them produces a script that runs
the whole training and writes the same artifacts.

The markdown cells become comment blocks, so the file still explains
itself.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NB = ROOT / "notebooks" / "crynet_training.ipynb"
OUT = ROOT / "notebooks" / "crynet_training_kaggle.py"

BANNER = """# ============================================================================
# CryNet - infant cry detection for ESP32-S3
#
# Generated from notebooks/crynet_training.ipynb by research/export_single_cell.py.
# Do not edit this file: edit research/build_notebook.py and regenerate.
#
# On Kaggle: attach the loud-speech corpus as an input dataset (the notebook
# finds speech__fsd50k_speech.zip under /kaggle/input by itself), set the
# accelerator to GPU T4 and the internet to On, then Run All.  The last cell
# writes crynet_artifacts.zip into the working directory; download it from
# the Output tab of the saved version.
# ============================================================================

"""


def main() -> int:
    nb = json.loads(NB.read_text(encoding="utf-8"))
    parts = [BANNER]
    for cell in nb["cells"]:
        body = cell["source"]
        text = body if isinstance(body, str) else "\n".join(body)
        if cell["cell_type"] == "markdown":
            lines = ["", "# " + "-" * 74, "#"]
            for line in text.split("\n"):
                lines.append("# " + line if line.strip() else "#")
            lines.append("# " + "-" * 74)
            parts.append("\n".join(lines))
        else:
            parts.append("\n# " + "-" * 74 + "\n" + text + "\n")
    OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")
    n_code = sum(1 for c in nb["cells"] if c["cell_type"] == "code")
    print(f"wrote {OUT}  ({n_code} code cells, "
          f"{len(OUT.read_text(encoding='utf-8').splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
